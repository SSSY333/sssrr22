    const base = fresh.length ? fresh : ok, top = Math.max(...base.map(p => p.w));
    const pool = base.filter(p => p.w >= top - 1);
    let tot = pool.reduce((a, p) => a + p.w, 0), r = Math.random() * tot;
    for (const p of pool) { r -= p.w; if (r <= 0) return p; }
    return pool[0];
